"""vault.py - the doer's own password vault: one KeePass (.kdbx) file, pure Python.

The agent that drives the browser never sees a password. Only login_fill.py (a plain script,
no model) opens this file, and only to type a login into the page it was pointed at. The
file holds ONLY the logins the owner chose to put here; Google Password Manager stays his.

  File : assistant/data/doer/agent.kdbx        (git-ignored; mirrored by the rescue kit)
  Key  : Windows Credential Manager, service "the owner-assistant", name "kdbx:agent"
         (generated by `init`; `key` prints it so the owner can open the file in KeePassXC)

the owner runs these himself, in a terminal:
  vault.py init                                   create the file + key (idempotent)
  vault.py import-chrome <passwords.csv>          Google Password Manager export (then delete the CSV)
  vault.py add <title> --url URL --username U [--totp]   password typed hidden, never on argv
  vault.py list                                   titles, hosts, usernames (no secrets)
  vault.py has <url>                              which entry a page would use
  vault.py remove <title>
  vault.py key                                    the master key (for KeePassXC), hidden from logs
  vault.py status                                 one line for the connection check

Per-site overrides go in an entry's Notes as JSON: {"user_sel": "#email", "pass_sel": "#pw",
"submit_sel": "button[type=submit]", "login_url": "https://...", "two_step": true}.
"""
from __future__ import annotations

import argparse
import csv
import getpass
import json
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import urlparse

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent                                   # assistant/
sys.path.insert(0, str(ROOT / "scripts"))
from alib import KEYRING_SERVICE, ensure_venv  # noqa: E402

DATA = Path(os.environ["DOER_DATA"]) if os.environ.get("DOER_DATA") else ROOT / "data" / "doer"
KDBX = DATA / "agent.kdbx"
KEY_NAME = "kdbx:agent"
GROUP = "Agent"


# ------------------------------------------------------------------ key
def _key_get() -> str | None:
    if os.environ.get("DOER_VAULT_KEY"):             # tests only
        return os.environ["DOER_VAULT_KEY"]
    ensure_venv()
    import keyring
    try:
        return keyring.get_password(KEYRING_SERVICE, KEY_NAME)
    except Exception:
        return None


def _key_set(val: str) -> None:
    if os.environ.get("DOER_VAULT_KEY") is not None:
        os.environ["DOER_VAULT_KEY"] = val
        return
    ensure_venv()
    import keyring
    keyring.set_password(KEYRING_SERVICE, KEY_NAME, val)


# ------------------------------------------------------------------ open
def exists() -> bool:
    return KDBX.exists()


def _open(create: bool = False):
    ensure_venv()
    from pykeepass import PyKeePass, create_database
    key = _key_get()
    if KDBX.exists():
        if not key:
            raise RuntimeError("vault file exists but its key is missing from Credential Manager (kdbx:agent)")
        return PyKeePass(str(KDBX), password=key)
    if not create:
        raise FileNotFoundError("no vault yet: python assistant/doer/vault.py init")
    if not key:
        key = secrets.token_urlsafe(32)
        _key_set(key)
    KDBX.parent.mkdir(parents=True, exist_ok=True)
    kp = create_database(str(KDBX), password=key)
    kp.add_group(kp.root_group, GROUP)
    kp.save()
    return kp


def _group(kp):
    g = kp.find_groups(name=GROUP, first=True)
    return g or kp.add_group(kp.root_group, GROUP)


# ------------------------------------------------------------------ host matching
def host_of(url: str) -> str:
    u = str(url or "").strip()
    if "://" not in u:
        u = "https://" + u
    return (urlparse(u).hostname or "").lower()


def _base(host: str) -> str:
    """registrable-ish domain: last two labels (three for co.uk-style)."""
    parts = host.split(".")
    if len(parts) >= 3 and parts[-2] in ("co", "com", "org", "gov", "net", "ac") and len(parts[-1]) == 2:
        return ".".join(parts[-3:])
    return ".".join(parts[-2:]) if len(parts) >= 2 else host


def _entry_hosts(e) -> list:
    hosts = [host_of(e.url or "")]
    try:
        o = json.loads(e.notes or "{}")
        if isinstance(o, dict) and o.get("login_url"):
            hosts.append(host_of(o["login_url"]))
        for h in (o.get("hosts") or []) if isinstance(o, dict) else []:
            hosts.append(str(h).lower())
    except ValueError:
        pass
    return [h for h in hosts if h]


def _path_of(url: str) -> str:
    u = str(url or "").strip()
    if "://" not in u:
        u = "https://" + u
    return (urlparse(u).path or "/").rstrip("/") or "/"


def find_for_url(kp, url: str):
    """Best entry for a page. Rank: same host + same path > same host + the entry's path is a
    prefix of the page's > same host > same registrable domain. Two logins on one host (a
    portal and its admin side) are told apart by their saved URL path."""
    host = host_of(url)
    if not host:
        return None
    path = _path_of(url)
    best, best_score = None, 0
    for e in _group(kp).entries:
        hs = _entry_hosts(e)
        score = 0
        if host in hs:
            score = 2
            ep = _path_of(e.url or "")
            if ep == path:
                score = 4
            elif ep != "/" and ep.split("/")[1] == path.split("/")[1]:      # same first path segment (/admin/...)
                score = 3
        elif any(_base(h) == _base(host) for h in hs):
            score = 1
        if score > best_score:
            best, best_score = e, score
    return best


def overrides(e) -> dict:
    try:
        o = json.loads(e.notes or "{}")
        return o if isinstance(o, dict) else {}
    except ValueError:
        return {}


# ------------------------------------------------------------------ commands (no secrets printed)
def cmd_init() -> int:
    kp = _open(create=True)
    print(f"vault ready: {KDBX} ({len(_group(kp).entries)} logins)")
    return 0


def cmd_import_chrome(path: str) -> int:
    p = Path(path)
    if not p.exists():
        print(f"no such file: {p}")
        return 1
    kp = _open(create=True)
    g = _group(kp)
    have = {(e.title, e.username) for e in g.entries}
    n = 0
    with p.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            url, user, pw = (row.get("url") or "").strip(), (row.get("username") or "").strip(), row.get("password") or ""
            if not url or not pw:
                continue
            title = (row.get("name") or host_of(url) or url).strip()
            if (title, user) in have:
                continue
            kp.add_entry(g, title, user, pw, url=url, notes=(row.get("note") or "").strip() or None)
            have.add((title, user))
            n += 1
    kp.save()
    print(f"imported {n} logins into {KDBX.name} ({len(g.entries)} total). Now DELETE {p} - it is plain text.")
    return 0


def cmd_add(title: str, url: str, username: str, totp: bool) -> int:
    kp = _open(create=True)
    g = _group(kp)
    pw = getpass.getpass(f"password for {title} (hidden): ")
    if not pw:
        print("nothing entered")
        return 1
    e = kp.add_entry(g, title, username, pw, url=url)
    if totp:
        secret = getpass.getpass("TOTP secret (base32, from the site's 'can't scan?' link; hidden): ").replace(" ", "")
        if secret:
            e.otp = f"otpauth://totp/{title}?secret={secret}"
    kp.save()
    print(f"added {title} ({host_of(url)}, {username}){' with TOTP' if totp else ''}")
    return 0


def cmd_add_stdin() -> int:
    """A login handed over by a Chat dialog (gchat_events vault_add_submit, sage-core 2026-10-28): ONE JSON object on
    stdin {site|url, username, password, totp?}; never on argv, never printed, never logged. Prints one line:
    ADDED <title> <host> <username> totp=yes|no, or VAULT_ERROR <reason>."""
    try:
        d = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        print("VAULT_ERROR bad json")
        return 1
    url = str(d.get("url") or d.get("site") or "").strip()
    user = str(d.get("username") or "").strip()
    pw = str(d.get("password") or "")
    totp = str(d.get("totp") or "").replace(" ", "").strip()
    if not url or not user or not pw:
        print("VAULT_ERROR site, username and password are all needed")
        return 1
    host = host_of(url)
    if not host or "." not in host:
        print("VAULT_ERROR the site needs a web address (like stripe.com)")
        return 1
    title = str(d.get("title") or host.split(".")[-2].capitalize() if host.count(".") >= 1 else host)
    kp = _open(create=True)
    g = _group(kp)
    for e in list(g.entries):
        if (e.username or "") == user and host_of(e.url or "") == host:
            kp.delete_entry(e)                        # a re-entered login replaces the old one for that site + user
    e = kp.add_entry(g, title, user, pw, url=url if "://" in url else "https://" + url)
    if totp:
        e.otp = f"otpauth://totp/{title}?secret={totp}"
    kp.save()
    print(f"ADDED {title} {host} {user} totp={'yes' if totp else 'no'}")
    return 0


def cmd_list() -> int:
    kp = _open()
    rows = sorted(_group(kp).entries, key=lambda e: (e.title or "").lower())
    for e in rows:
        print(f"{(e.title or '')[:30]:<30} {host_of(e.url or ''):<32} {(e.username or '')[:32]:<32} {'TOTP' if e.otp else ''}")
    print(f"({len(rows)} logins)")
    return 0


def cmd_has(url: str) -> int:
    kp = _open()
    e = find_for_url(kp, url)
    if not e:
        print(f"NO_ENTRY {host_of(url)}")
        return 1
    print(f"ENTRY {e.title} user={e.username} totp={'yes' if e.otp else 'no'}")
    return 0


def cmd_remove(title: str) -> int:
    kp = _open()
    e = kp.find_entries(title=title, group=_group(kp), first=True)
    if not e:
        print("not found")
        return 1
    kp.delete_entry(e)
    kp.save()
    print(f"removed {title}")
    return 0


def cmd_key() -> int:
    k = _key_get()
    if not k:
        print("no key stored")
        return 1
    print(k)
    return 0


def cmd_status() -> int:
    """For conn_check (cmd_output): a line = live, nothing = not configured, exit 1 = dead."""
    if not KDBX.exists():
        return 0
    try:
        kp = _open()
    except Exception as e:  # noqa: BLE001
        print(f"ERROR {type(e).__name__}", file=sys.stderr)
        return 1
    n = len(_group(kp).entries)
    print(f"{n} login{'s' if n != 1 else ''} in agent.kdbx")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init")
    p = sub.add_parser("import-chrome"); p.add_argument("csv")
    p = sub.add_parser("add"); p.add_argument("title"); p.add_argument("--url", required=True); p.add_argument("--username", required=True); p.add_argument("--totp", action="store_true")
    sub.add_parser("add-stdin", help="one JSON login on stdin (the Chat dialog path); prints ADDED or VAULT_ERROR")
    sub.add_parser("list")
    p = sub.add_parser("has"); p.add_argument("url")
    p = sub.add_parser("remove"); p.add_argument("title")
    sub.add_parser("key")
    sub.add_parser("status")
    a = ap.parse_args()
    if a.cmd == "init":
        return cmd_init()
    if a.cmd == "import-chrome":
        return cmd_import_chrome(a.csv)
    if a.cmd == "add":
        return cmd_add(a.title, a.url, a.username, a.totp)
    if a.cmd == "add-stdin":
        return cmd_add_stdin()
    if a.cmd == "list":
        return cmd_list()
    if a.cmd == "has":
        return cmd_has(a.url)
    if a.cmd == "remove":
        return cmd_remove(a.title)
    if a.cmd == "key":
        return cmd_key()
    if a.cmd == "status":
        return cmd_status()
    return 2


if __name__ == "__main__":
    sys.exit(main())
